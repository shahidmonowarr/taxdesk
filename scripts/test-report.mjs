// Runs every suite and writes TEST_RESULTS.md from their JUnit output.
// Usage: npm run test:report
//
// Each suite runs even if an earlier one fails, and the report records what
// actually happened — a failing run produces a report that says so.
import "dotenv/config";
import { execSync, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";

const OUT = "test-results";
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const suites = [
  {
    key: "unit",
    title: "Unit",
    what: "Validation rules, password hashing, session tokens, open-redirect guard. No database.",
    cmd: `npx vitest run --project unit --reporter=default --reporter=junit --outputFile.junit=${OUT}/unit-junit.xml`,
  },
  {
    key: "integration",
    title: "Integration",
    what: "Services against a real PostgreSQL database: auth, sessions, rate limiting, CRUD, cross-user isolation.",
    cmd: `npx vitest run --project integration --reporter=default --reporter=junit --outputFile.junit=${OUT}/integration-junit.xml`,
  },
  {
    key: "e2e",
    title: "End-to-end",
    what: "Playwright in Chromium against a production build (`next build && next start`) on the test database.",
    cmd: "npx playwright test",
  },
];

const sh = (cmd) => {
  try {
    return execSync(cmd, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "unknown";
  }
};

const decode = (s) =>
  s.replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");

function parse(file) {
  if (!existsSync(file)) return null;
  const xml = readFileSync(file, "utf8");
  const cases = [];
  const re = /<testcase\b([^>]*?)(?:\/>|>([\s\S]*?)<\/testcase>)/g;
  for (const m of xml.matchAll(re)) {
    const attrs = m[1];
    const body = m[2] ?? "";
    const get = (n) => decode(attrs.match(new RegExp(`\\b${n}="([^"]*)"`))?.[1] ?? "");
    const status = /<(failure|error)\b/.test(body) ? "fail" : /<skipped\b/.test(body) ? "skip" : "pass";
    cases.push({ group: get("classname"), name: get("name"), time: Number(get("time") || 0), status });
  }
  return cases;
}

const started = Date.now();
const results = suites.map((s) => {
  console.log(`\n▶ ${s.title}\n`);
  const t0 = Date.now();
  const run = spawnSync(s.cmd, { shell: true, stdio: "inherit", env: { ...process.env, CI: "" } });
  const cases = parse(`${OUT}/${s.key}-junit.xml`) ?? [];
  return { ...s, cases, exitCode: run.status, seconds: (Date.now() - t0) / 1000 };
});

const count = (cases, st) => cases.filter((c) => c.status === st).length;
const total = results.reduce((n, r) => n + r.cases.length, 0);
const failed = results.reduce((n, r) => n + count(r.cases, "fail"), 0);
const allGreen = results.every((r) => r.exitCode === 0 && r.cases.length > 0 && count(r.cases, "fail") === 0);

const pgVersion = (() => {
  const v = sh(
    `node -e "const {Client}=require('pg');const c=new Client({connectionString:process.env.TEST_DATABASE_URL});c.connect().then(()=>c.query('show server_version')).then(r=>{console.log(r.rows[0].server_version);return c.end()})" `,
  );
  return v.split("\n").pop();
})();

const icon = { pass: "✅", fail: "❌", skip: "⏭️" };
const lines = [];
lines.push("# Test results", "");
lines.push(
  `**${allGreen ? "✅ All suites passed" : "❌ Some suites failed"}** · ${total} tests · ${failed} failed · generated ${new Date().toISOString().replace(/\.\d+Z$/, "Z")}`,
  "",
);
lines.push(
  "> Generated by `npm run test:report`, which runs every suite locally and writes this file from the JUnit output.",
  "",
);
lines.push("| Suite | Tests | Passed | Failed | Time | Covers |", "|---|---:|---:|---:|---:|---|");
for (const r of results) {
  lines.push(
    `| ${r.title} | ${r.cases.length} | ${count(r.cases, "pass")} | ${count(r.cases, "fail")} | ${r.seconds.toFixed(1)}s | ${r.what} |`,
  );
}
lines.push("", "## Environment", "");
lines.push("| | |", "|---|---|");
lines.push(`| Commit | \`${sh("git rev-parse --short HEAD")}\` (${sh("git log -1 --format=%s")}) |`);
lines.push(`| Node.js | ${process.version} |`);
lines.push(`| PostgreSQL | ${pgVersion} |`);
lines.push(`| Playwright | ${sh("npx playwright --version")} (Chromium) |`);
lines.push(`| OS | ${os.type()} ${os.release()} (${os.arch()}) |`);
lines.push(`| Total wall time | ${((Date.now() - started) / 1000).toFixed(0)}s (includes the production build for e2e) |`);

for (const r of results) {
  lines.push("", `## ${r.title} — ${count(r.cases, "pass")}/${r.cases.length}`, "");
  if (r.cases.length === 0) {
    lines.push(`_No results recorded (exit code ${r.exitCode})._`);
    continue;
  }
  const groups = Map.groupBy(r.cases, (c) => c.group);
  for (const [group, cases] of groups) {
    lines.push(`**${group}**`, "");
    for (const c of cases) lines.push(`- ${icon[c.status]} ${c.name}`);
    lines.push("");
  }
  while (lines.at(-1) === "") lines.pop();
}

writeFileSync("TEST_RESULTS.md", lines.join("\n").trimEnd() + "\n");
console.log(`\nWrote TEST_RESULTS.md — ${total} tests, ${failed} failed.`);
process.exit(allGreen ? 0 : 1);
